// Tablica operacji kontraktu dla `call` (src/api/client.ts): `writeOperations` z src/api/openapi.json pisze
// src/api/generated/operations.gen.ts, gdzie każda operacja (`operationId`) ma metodę, adres `…Data["url"]`
// i schemat odpowiedzi `z…Response`, które wygenerował @hey-api/openapi-ts. Nazwę, której hey-api nie
// wygenerował, generator odrzuca, a adres sprawdza typecheck (`satisfies`) z typem `…Data` operacji.
import { readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const api = resolve(import.meta.dirname, "../src/api")

const generated = join(api, "generated")

function pascal(name) {
  return name[0].toUpperCase() + name.slice(1)
}

function exported(source, kind, name) {
  if (!new RegExp(`^export ${kind} ${name} = `, "m").test(source)) {
    throw new Error(`hey-api nie wygenerował ${name}: zmienił się jego sposób nazywania operacji.`)
  }

  return name
}

export function writeOperations() {
  const contract = JSON.parse(readFileSync(join(api, "openapi.json"), "utf8"))
  const types = readFileSync(join(generated, "types.gen.ts"), "utf8")
  const schemas = readFileSync(join(generated, "zod.gen.ts"), "utf8")

  const operations = Object.entries(contract.paths)
    .flatMap(([url, methods]) =>
      Object.entries(methods).map(([method, operation]) => ({
        name: operation.operationId,
        method: method.toUpperCase(),
        url,
        data: exported(types, "type", `${pascal(operation.operationId)}Data`),
        response: exported(schemas, "const", `z${pascal(operation.operationId)}Response`),
      }))
    )
    .toSorted((left, right) => (left.name < right.name ? -1 : 1))

  const lines = [
    "// This file is auto-generated by scripts/operations.mjs",
    "",
    'import type * as z from "zod"',
    "",
    `import type { ${operations.map(({ data }) => data).join(", ")} } from "./types.gen"`,
    `import { ${operations.map(({ response }) => response).join(", ")} } from "./zod.gen"`,
    "",
    "export type OperationData = {",
    ...operations.map(({ name, data }) => `  ${name}: ${data}`),
    "}",
    "",
    "export const operations = {",
    ...operations.map(
      ({ name, method, url, response }) => `  ${name}: { method: "${method}", url: "${url}", response: ${response} },`
    ),
    "} as const satisfies {",
    '  [O in keyof OperationData]: { method: string; url: OperationData[O]["url"]; response: z.ZodType }',
    "}",
    "",
  ]

  writeFileSync(join(generated, "operations.gen.ts"), lines.join("\n"))
}
